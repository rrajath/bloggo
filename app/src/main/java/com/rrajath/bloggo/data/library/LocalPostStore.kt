package com.rrajath.bloggo.data.library

import android.content.Context
import com.rrajath.bloggo.model.DocKind
import com.rrajath.bloggo.model.Post
import com.rrajath.bloggo.model.PostState
import java.io.File
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

private const val LOCAL_POSTS_DIR = "local-posts"

/**
 * Durable storage for a post or page that only exists on this device —
 * the fix for the data-loss bug where `posts` (`BloggoApp.kt`) was pure
 * in-memory Compose state: a local draft survived only as long as the
 * process did, so Android reclaiming a backgrounded app silently lost
 * whatever hadn't been pushed to the repo yet.
 *
 * Every save writes a real markdown file under `context.filesDir` — the same
 * shape [com.rrajath.bloggo.data.publish.PostPublishRepository] eventually
 * commits, so nothing changes about the file the moment it's pushed — and
 * indexes it in [LocalPostDao] for fast listing without reading every file
 * on startup. [context.filesDir] specifically, not `cacheDir`: unlike staged
 * media bytes (`MediaStaging.kt`), which are trivially re-derivable from a
 * `content://` Uri and so belong behind a cache the OS is free to reclaim, an
 * unpublished draft is not recoverable from anywhere else once it's gone.
 *
 * The hard invariant this whole class exists to uphold: a file it wrote is
 * never removed except by [delete], and every call to [delete] in this
 * codebase is a direct result of the writer tapping an explicit delete
 * action. Nothing here runs a reconciliation pass, and nothing in
 * `PostLibraryRepository`/`PageLibraryRepository` (remote sync) or this
 * store's own [loadAll] (startup) ever calls [delete].
 */
class LocalPostStore(
  private val context: Context,
  private val localPostDao: LocalPostDao,
) {
  private val directory: File
    get() = File(context.filesDir, LOCAL_POSTS_DIR).apply { mkdirs() }

  /** Every locally-stored post/page, file contents included, as real [Post]s
   * ready to merge into `BloggoApp`'s in-memory list. Called once, at cold
   * start; never removes a row or file, so a file this returns keeps existing
   * on disk regardless of what the caller does with the [Post] it became. */
  suspend fun loadAll(): List<Post> = withContext(Dispatchers.IO) {
    localPostDao.getAll().mapNotNull { entity ->
      // A row whose file is gone (e.g. filesDir cleared by the user from
      // system Settings) is dropped from the result rather than surfaced as
      // a blank post; there is nothing to reconstruct it from either way.
      val markdown = runCatching { File(entity.filePath).readText() }.getOrNull() ?: return@mapNotNull null
      entity.toPost(markdown)
    }
  }

  /** Writes [post]'s markdown to its file and upserts its index row. Safe to
   * call on every edit — an [Upsert] and a single file write, not a scan of
   * anything else stored here. Callers are expected to have already checked
   * this post isn't pushed yet (`Post.isPushed`); this itself doesn't guard
   * that, so a caller that wants remote posts to stay entirely out of this
   * table is responsible for that check before calling. */
  suspend fun save(post: Post) = withContext(Dispatchers.IO) {
    val file = File(directory, "${post.slug.fileSafe()}.md")
    file.writeText(post.markdown)
    localPostDao.upsert(
      LocalPostEntity(
        slug = post.slug,
        kind = post.kind.name,
        title = post.title,
        filePath = file.absolutePath,
        wordCount = post.wordCount,
        date = post.date,
        dateMillis = post.dateMillis,
        updatedAt = post.updatedAt,
        editedAgo = post.editedAgo,
      )
    )
  }

  /** Removes [slug]'s file and index row for good. Every call site of this
   * must be a direct, explicit user delete action — see this class's own doc
   * comment for why that's a hard invariant, not a convention. */
  suspend fun delete(slug: String) = withContext(Dispatchers.IO) {
    File(directory, "${slug.fileSafe()}.md").delete()
    localPostDao.deleteBySlug(slug)
  }

  /** [Post.slug] is generated by this app itself (`slugify` plus a timestamp,
   * or a fixed `untitled`/`untitled-page` stem) and so is already filesystem-
   * safe in practice; this is a defensive backstop, not something normal
   * slugs ever need. */
  private fun String.fileSafe(): String = replace(Regex("[^A-Za-z0-9._-]"), "_")
}

private fun LocalPostEntity.toPost(markdown: String): Post = Post(
  slug = slug,
  title = title,
  // Every row in this table is, by construction, a post or page that has
  // never been pushed (see LocalPostStore's own doc comment) — so unlike the
  // remote caches' toPost()/toPage(), there's no frontmatter `draft:` flag or
  // separate published state to read here: Draft is what "local-only" means.
  state = PostState.Draft,
  kind = runCatching { DocKind.valueOf(kind) }.getOrDefault(DocKind.Post),
  markdown = markdown,
  wordCount = wordCount,
  date = date,
  editedAgo = editedAgo,
  updatedAt = updatedAt,
  dateMillis = dateMillis,
  // repoPath is deliberately left null: a row here has never been committed.
  // The moment it is (Post.repoPath gets set), BloggoApp.updatePost stops
  // calling save() for this slug, per Post.isPushed — this store's copy of
  // it simply stops being written to, rather than being deleted.
)
